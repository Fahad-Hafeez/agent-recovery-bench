def load():
    with open("results/report_main.json", encoding="utf-8") as fh:
        rep = json.load(fh)
    rows = []
    with open("results/episodes.jsonl", encoding="utf-8") as fh:
        for line in fh:
            if line.strip():
                rows.append(json.loads(line))
    return rep, rows


def _fit_tables(tex: str) -> str:
    """Wrap each tabular in a max-width box.

    The journal text area (elsarticle, single column) is narrower than the layout
    these tables were first built for. Max-width scaling shrinks only a table that
    would run past the margin and leaves a narrow table at its natural size.
    """
    open_box = r"\begin{adjustbox}{max width=\textwidth}" + "\n"
    close_box = "\n" + r"\end{adjustbox}"
    return (tex.replace(r"\begin{tabular}", open_box + r"\begin{tabular}")
               .replace(r"\end{tabular}", r"\end{tabular}" + close_box))


def emit(name: str, body: str, full: str):
    """Write both a standalone table and a body-only fragment for embedding."""
    with open(os.path.join(GEN, f"{name}_body.tex"), "w", encoding="utf-8",
              newline="\n") as fh:
        fh.write(body.rstrip() + "\n")
    with open(os.path.join(GEN, f"{name}.tex"), "w", encoding="utf-8",
              newline="\n") as fh:
        fh.write(_fit_tables(full))


def esc(s: str) -> str:
    return s.replace("_", r"\_")


def fmt(x, nd=3, pct=False):
    if x is None:
        return "--"
    if pct:
        return f"{100 * x:.1f}"
    return f"{x:.{nd}f}"


def save_fig(fig, name: str) -> None:
    """Write a figure with no embedded timestamp, so a rerun is byte-identical.

    Matplotlib stamps CreationDate/ModDate into the PDF; leaving them in makes the
    released figures differ on every rerun and breaks the claim that regenerating
    the paper leaves a clean git diff.
    """
    fig.savefig(os.path.join(FIG, name),
                metadata={"CreationDate": None, "ModDate": None,
                          "Producer": None, "Creator": None})
    plt.close(fig)


def ci_cell(rec, key="recovery_rate", pct=True):
    lo, hi = rec.get("lo"), rec.get("hi")
    if rec.get(key) is None:
        return "--"
    return f"{fmt(rec[key], pct=pct)} [{fmt(lo, pct=pct)}, {fmt(hi, pct=pct)}]"


