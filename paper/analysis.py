    ax.hist(np.clip(vals, -0.5, 8), bins=bins, color="#3b6ea5", edgecolor="white", lw=0.5)
    ax.set_xlabel("Detection delay (steps after injection)")
    ax.set_ylabel("Episodes")
    ax.grid(axis="y", lw=0.3, alpha=0.5)
    ax.set_yscale("log")
    save_fig(fig, "fig_ttd.pdf")


