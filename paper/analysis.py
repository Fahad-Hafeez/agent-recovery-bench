def _sci(p: float) -> str:
    """LaTeX for a tiny p-value: three decimals down to 0.001, then one digit."""
    if p >= 0.001:
        return f"{p:.3f}"
    exp = int(np.floor(np.log10(p)))
    return rf"\ensuremath{{{p / 10 ** exp:.1f}\times10^{{{exp}}}}}"


