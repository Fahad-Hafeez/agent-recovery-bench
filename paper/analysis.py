def _outcomes(rows):
    """Index policy outcomes by the pair they were scored on."""
    main = [r for r in rows if r.get("tag") == "policy_pass" and r.get("fault") != "none"]
    idx: dict[tuple, dict[str, bool]] = defaultdict(dict)
    for r in main:
        idx[(r["family"], r["template"], r["config"], r["seed"], r["fault"])][r["policy"]] = bool(r["success"])
    return idx


def _paired_test(idx, a: str, b: str, keep=None) -> dict:
    keys = [k for k, v in idx.items() if a in v and b in v and (keep is None or keep(k))]
    res = mcnemar([idx[k][a] for k in keys], [idx[k][b] for k in keys])
    return {"a": a, "b": b, "n_pairs": res["n"], "a_only": res["a_only"],
            "b_only": res["b_only"], "n_discordant": res["n_discordant"],
            "p_value": res["p_value"]}


def _p(x) -> str:
    if x is None:
        return "--"
    if x < 0.001:
        return r"\ensuremath{<}0.001"
    return f"{x:.3f}"


def _pct_ci(rec) -> str:
    """``60.9 [58.8, 65.3]``, or just the point estimate when no interval exists."""
    if not rec or rec.get("recovery_rate") is None:
        return "--"
    v, lo, hi = rec["recovery_rate"], rec.get("lo"), rec.get("hi")
    if v != v:
        return "--"
    if lo is None or lo != lo or hi is None or hi != hi:
        return f"{100 * v:.1f}"
    return f"{100 * v:.1f} [{100 * lo:.1f}, {100 * hi:.1f}]"


def write_stats(rows) -> None:
    """McNemar tests over policy pairs, plus per-class and per-family contrasts.

    Each family of tests is corrected separately with Holm: the six policy pairs are
    one family, the seven per-class rule-vs-ranker contrasts another, the four
    per-family contrasts a third. Correcting across everything at once would
    answer a question nobody asked ("is any of these contrasts significant?").
    """
    idx = _outcomes(rows)
    pols = ("no_recovery", "retry_only", "rule_based", "model_based")
    policy_tests = [_paired_test(idx, a, b) for a, b in itertools.combinations(pols, 2)]
    adj = holm({f"{t['a']}|{t['b']}": t["p_value"] for t in policy_tests})
    for t in policy_tests:
        t["p_holm"] = adj[f"{t['a']}|{t['b']}"]

    class_tests = []
    for ft in TYPES:
        t = _paired_test(idx, "rule_based", "model_based", lambda k, ft=ft: k[4] == ft)
        t["fault"] = ft
        class_tests.append(t)
    cadj = holm({t["fault"]: t["p_value"] for t in class_tests})
    for t in class_tests:
        t["p_holm"] = cadj[t["fault"]]

    fam_tests = []
    for fam in sorted({k[0] for k in idx}):
        t = _paired_test(idx, "rule_based", "model_based", lambda k, fam=fam: k[0] == fam)
        t["family"] = fam
        fam_tests.append(t)
    fadj = holm({t["family"]: t["p_value"] for t in fam_tests})
    for t in fam_tests:
        t["p_holm"] = fadj[t["family"]]

    def find(a: str, b: str) -> dict:
        return next(t for t in policy_tests if t["a"] == a and t["b"] == b)

    # ``combinations`` keeps the policy order, so each pair is (a, b) with a earlier.
    # a_only is therefore "only a recovered"; for the ranker contrast a is the rules.
    rm = find("rule_based", "model_based")
    rn = find("no_recovery", "rule_based")
    mn = find("no_recovery", "model_based")
    n_class_sig = sum(1 for t in class_tests if t["p_holm"] < 0.05)
    n_fam_sig = sum(1 for t in fam_tests if t["p_holm"] < 0.05)

    macros = [
        "% Auto-generated by paper/analysis.py -- do not edit.",
        f"\\newcommand{{\\StatsPairs}}{{{rm['n_pairs']:,}}}",
        f"\\newcommand{{\\RuleVsModelB}}{{{rm['a_only']:,}}}",
        f"\\newcommand{{\\RuleVsModelC}}{{{rm['b_only']:,}}}",
        f"\\newcommand{{\\RuleVsModelP}}{{{_p(rm['p_value'])}}}",
        f"\\newcommand{{\\RuleVsModelPHolm}}{{{_p(rm['p_holm'])}}}",
        f"\\newcommand{{\\RuleVsNoRecoveryP}}{{{_p(rn['p_value'])}}}",
        f"\\newcommand{{\\RuleVsNoRecoveryPHolm}}{{{_p(rn['p_holm'])}}}",
        f"\\newcommand{{\\ModelVsNoRecoveryP}}{{{_p(mn['p_value'])}}}",
        f"\\newcommand{{\\HolmPolicyTests}}{{{len(policy_tests)}}}",
        f"\\newcommand{{\\HolmClassTests}}{{{len(class_tests)}}}",
        f"\\newcommand{{\\HolmClassSignificant}}{{{n_class_sig}}}",
        f"\\newcommand{{\\HolmFamilyTests}}{{{len(fam_tests)}}}",
        f"\\newcommand{{\\HolmFamilySignificant}}{{{n_fam_sig}}}",
    ]
    with open(os.path.join(GEN, "macros_stats.tex"), "w", encoding="utf-8",
              newline="\n") as fh:
        fh.write("\n".join(macros) + "\n")

    def rows_for(tests, label) -> str:
        out = []
        for t in tests:
            out.append(f"{label(t)} & {t['n_pairs']} & {t['a_only']} & {t['b_only']} & "
                       f"{_p(t['p_value'])} & {_p(t['p_holm'])} \\\\")
        return "\n".join(out)

    head = "Comparison & Pairs & $b$ & $c$ & $p$ & $p_{\\text{Holm}}$ \\\\"
    _full_table("tab_tests_policy", head, rows_for(
        policy_tests, lambda t: f"{POLICY_LABEL[t['a']]} vs {POLICY_LABEL[t['b']]}"),
        "Exact McNemar tests over the " + f"{rm['n_pairs']:,} harmful pairs: all six policy "
        "contrasts, Holm-corrected across the six. $b$ counts episodes the first system "
        "recovered and the second did not, $c$ the reverse. The canonical mapping beats the "
        "learned ranker: $b=" + f"{rm['a_only']}" + "$ against $c=" + f"{rm['b_only']}" + "$.",
        "tab:appendix_tests_policy", "@{}lrrrcc@{}")

    head_class = "Failure class & Pairs & $b$ (rules) & $c$ (ranker) & $p$ & $p_{\\text{Holm}}$ \\\\"
    _full_table("tab_tests_class", head_class, rows_for(
        class_tests, lambda t: esc(t["fault"])),
        "Per-class McNemar tests, rule-based versus model-based, Holm-corrected across the "
        "seven classes (significant in " + f"{n_class_sig}" + " of " + f"{len(class_tests)}"
        + "). Where the two policies differ at all, they differ in favour of the canonical "
        "mapping; the remaining classes agree closely, which is the claim the class table "
        "makes: repair depends on the operator, not the selector.",
        "tab:appendix_tests_class", "@{}lrrrcc@{}")

    _full_table("tab_tests_family", head_class.replace("Failure class", "Family"),
                rows_for(fam_tests, lambda t: t["family"]),
                "Per-family McNemar tests, rule-based versus model-based, Holm-corrected across "
                "the four families (significant in " + f"{n_fam_sig}" + " of "
                + f"{len(fam_tests)}" + ").",
                "tab:appendix_tests_family", "@{}lrrrcc@{}")


