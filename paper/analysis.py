def fig_recovery_by_type(rep):
    idx = {(r["fault"], r["policy"]): r for r in rep["recovery_by_type"]}
    pols = ["no_recovery", "retry_only", "rule_based", "model_based"]
    x = np.arange(len(TYPES))
    w = 0.2
    fig, ax = plt.subplots(figsize=(7.0, 2.6))
    for i, pol in enumerate(pols):
        vals, errs = [], []
        for ft in TYPES:
            r = idx.get((ft, pol), {})
            v = r.get("recovery_rate")
            vals.append(0 if v is None else 100 * v)
            lo, hi = r.get("lo"), r.get("hi")
            errs.append(0 if (lo is None or hi is None) else 100 * (hi - lo) / 2)
        ax.bar(x + (i - 1.5) * w, vals, w, yerr=errs, capsize=1.6,
               label=POLICY_LABEL[pol], color=COLORS[pol], ecolor="#444444",
               error_kw={"lw": 0.6})
    ax.set_xticks(x)
    ax.set_xticklabels([SHORT[t] for t in TYPES], rotation=0)
    ax.set_ylabel("Recovery rate (%)")
    ax.set_ylim(0, 105)
    ax.legend(ncol=4, frameon=False, fontsize=7.5, loc="upper center",
              bbox_to_anchor=(0.5, 1.22))
    ax.grid(axis="y", lw=0.3, alpha=0.5)
    save_fig(fig, "fig_bytype.pdf")


def fig_ttd(rows):
    g = [r["ttd"] for r in rows if r.get("detected") and r.get("ttd") is not None
         and r["policy"] == "rule_based" and r["tag"] == "policy_pass"]
    if not g:
        return
    vals = np.array(g)
    bins = np.arange(-0.5, min(vals.max(), 8) + 1.5, 1)
