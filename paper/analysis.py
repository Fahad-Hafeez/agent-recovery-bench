def extra_stats(rows):
    """Numbers the report does not carry directly, recomputed from episodes."""
    main = [r for r in rows if r["tag"] == "policy_pass" and r["fault"] != "none"]
    bb = [r for r in rows if r["tag"] == "blackbox" and r["fault"] != "none"]
    out = {}
    if bb:
        for pol in ("rule_based", "model_based"):
            g = [r for r in bb if r["policy"] == pol]
            if not g:
                continue
            ci = bootstrap_ci([1.0 if r["success"] else 0.0 for r in g],
                              [r["template"] for r in g], seed=2)
            out[f"blackbox_{pol}"] = ci
            out[f"blackbox_{pol}_detected"] = mean([1.0 if r["detected"] else 0.0 for r in g])
    # Detection-before-propagation: does ttd == 0 predict recovery?
    rb = [r for r in main if r["policy"] == "rule_based" and r["detected"]]
    early = [r for r in rb if (r["ttd"] or 0) <= 0]
    late = [r for r in rb if (r["ttd"] or 0) > 0]
    out["early_n"] = len(early)
    out["early_rec"] = mean([1.0 if r["success"] else 0.0 for r in early])
    out["late_n"] = len(late)
    out["late_rec"] = mean([1.0 if r["success"] else 0.0 for r in late])
    out["binary_ttd_n"] = len(rb) - len(early) - len(late)
    # Signal-level AUC of individual features, computed on the whole grid is not
    # possible post-hoc (features are not stored per step in episodes.jsonl).
    # Cost of false alarms: episodes where the detector fired before injection.
    out["early_alarm_rate"] = mean([1.0 if r.get("early_alarms", 0) else 0.0 for r in main])
    # Self-report by family
    by_fam = defaultdict(list)
    for r in main:
        by_fam[r["family"]].append(r)
    out["selfreport_by_family"] = {
        f: {
            "claimed": mean([1.0 if r["claimed"] else 0.0 for r in g]),
            "verified": mean([1.0 if r["success"] else 0.0 for r in g]),
        } for f, g in by_fam.items()
    }
    return out


